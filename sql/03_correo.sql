/* =====================================================================
   Banbaj · 03 Correo dinámico (esquema mail)
   ---------------------------------------------------------------------
   Las listas de distribución dejan de estar escritas en los .prg.
   Para cambiar a quién le llega un correo solo se editan filas de
   mail.DESTINATARIO (o se usan mail.sp_destinatario_alta / _baja).

   LISTA         -> grupo de destinatarios (ej. RETIROS_ACT_486)
   DESTINATARIO  -> correo + tipo (TO / CC / BCC) + vigencia
   FRAGMENTO     -> HTML reutilizable (firma, aviso de confidencialidad)
   PLANTILLA     -> asunto y cuerpo con marcadores {{FECHA}}, {{FRAG:FIRMA_486}}…
   ENVIO         -> registro de cada envío
   Requiere Database Mail configurado con un perfil (PERFIL_DBMAIL).
   ===================================================================== */
SET NOCOUNT ON;
GO
IF OBJECT_ID('mail.LISTA') IS NULL
CREATE TABLE mail.LISTA (
    CODIGO       VARCHAR(60)   NOT NULL CONSTRAINT PK_MAIL_LISTA PRIMARY KEY,
    CLIENTE      VARCHAR(10)   NOT NULL,
    DESCRIPCION  NVARCHAR(400) NULL,
    ACTIVO       BIT           NOT NULL CONSTRAINT DF_MAIL_LISTA_ACT DEFAULT 1
);
GO
IF OBJECT_ID('mail.DESTINATARIO') IS NULL
CREATE TABLE mail.DESTINATARIO (
    ID             INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_MAIL_DESTINATARIO PRIMARY KEY,
    LISTA          VARCHAR(60)   NOT NULL CONSTRAINT FK_MAIL_DESTINATARIO_LISTA REFERENCES mail.LISTA (CODIGO),
    EMAIL          VARCHAR(320)  NOT NULL,
    NOMBRE         NVARCHAR(150) NULL,
    TIPO           VARCHAR(3)    NOT NULL CONSTRAINT DF_MAIL_DESTINATARIO_TIPO DEFAULT 'TO',
    ACTIVO         BIT           NOT NULL CONSTRAINT DF_MAIL_DESTINATARIO_ACT DEFAULT 1,
    VIGENTE_DESDE  DATE          NOT NULL CONSTRAINT DF_MAIL_DESTINATARIO_DESDE DEFAULT CAST(GETDATE() AS DATE),
    VIGENTE_HASTA  DATE          NULL,
    FE_ALTA        DATETIME2(0)  NOT NULL CONSTRAINT DF_MAIL_DESTINATARIO_FE DEFAULT SYSDATETIME(),
    USUARIO_ALTA   SYSNAME       NOT NULL CONSTRAINT DF_MAIL_DESTINATARIO_USR DEFAULT SUSER_SNAME(),
    CONSTRAINT CK_MAIL_DESTINATARIO_TIPO  CHECK (TIPO IN ('TO','CC','BCC')),
    CONSTRAINT CK_MAIL_DESTINATARIO_EMAIL CHECK (EMAIL LIKE '%_@_%._%' AND EMAIL NOT LIKE '%[ ;,]%'),
    CONSTRAINT UX_MAIL_DESTINATARIO UNIQUE (LISTA, EMAIL, TIPO)
);
GO
IF OBJECT_ID('mail.FRAGMENTO') IS NULL
CREATE TABLE mail.FRAGMENTO (
    CODIGO  VARCHAR(60)    NOT NULL CONSTRAINT PK_MAIL_FRAGMENTO PRIMARY KEY,
    HTML    NVARCHAR(MAX)  NOT NULL
);
GO
IF OBJECT_ID('mail.PLANTILLA') IS NULL
CREATE TABLE mail.PLANTILLA (
    CODIGO         VARCHAR(60)    NOT NULL CONSTRAINT PK_MAIL_PLANTILLA PRIMARY KEY,
    LISTA          VARCHAR(60)    NOT NULL CONSTRAINT FK_MAIL_PLANTILLA_LISTA REFERENCES mail.LISTA (CODIGO),
    PERFIL_DBMAIL  SYSNAME        NOT NULL,
    ASUNTO         NVARCHAR(255)  NOT NULL,
    CUERPO_HTML    NVARCHAR(MAX)  NOT NULL,
    IMPORTANCIA    VARCHAR(6)     NOT NULL CONSTRAINT DF_MAIL_PLANTILLA_IMP DEFAULT 'Normal',
    ACTIVO         BIT            NOT NULL CONSTRAINT DF_MAIL_PLANTILLA_ACT DEFAULT 1,
    COMENTARIO     NVARCHAR(400)  NULL,
    CONSTRAINT CK_MAIL_PLANTILLA_IMP CHECK (IMPORTANCIA IN ('Low','Normal','High'))
);
GO
IF OBJECT_ID('mail.ENVIO') IS NULL
CREATE TABLE mail.ENVIO (
    ID           BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_MAIL_ENVIO PRIMARY KEY,
    ID_CORRIDA   INT            NULL,
    PLANTILLA    VARCHAR(60)    NOT NULL,
    PARA         NVARCHAR(MAX)  NULL,
    CC           NVARCHAR(MAX)  NULL,
    CCO          NVARCHAR(MAX)  NULL,
    ASUNTO       NVARCHAR(255)  NULL,
    ADJUNTOS     NVARCHAR(MAX)  NULL,
    MAILITEM_ID  INT            NULL,           -- msdb.dbo.sysmail_allitems
    ESTATUS      VARCHAR(15)    NOT NULL,       -- ENVIADO / PRUEBA / ERROR / SIN_DESTINO
    ERROR        NVARCHAR(4000) NULL,
    FECHA        DATETIME2(0)   NOT NULL CONSTRAINT DF_MAIL_ENVIO_FECHA DEFAULT SYSDATETIME()
);
GO

/* Destinatarios vigentes por lista, ya armados como los pide sp_send_dbmail */
CREATE OR ALTER VIEW mail.v_LISTA_RESUELTA
AS
SELECT  l.CODIGO AS LISTA,
        STRING_AGG(CASE WHEN d.TIPO = 'TO'  THEN CAST(d.EMAIL AS NVARCHAR(MAX)) END, ';') WITHIN GROUP (ORDER BY d.EMAIL) AS PARA,
        STRING_AGG(CASE WHEN d.TIPO = 'CC'  THEN CAST(d.EMAIL AS NVARCHAR(MAX)) END, ';') WITHIN GROUP (ORDER BY d.EMAIL) AS CC,
        STRING_AGG(CASE WHEN d.TIPO = 'BCC' THEN CAST(d.EMAIL AS NVARCHAR(MAX)) END, ';') WITHIN GROUP (ORDER BY d.EMAIL) AS CCO,
        COUNT(d.ID) AS DESTINATARIOS
FROM    mail.LISTA l
LEFT JOIN mail.DESTINATARIO d
       ON d.LISTA = l.CODIGO
      AND d.ACTIVO = 1
      AND d.VIGENTE_DESDE <= CAST(GETDATE() AS DATE)
      AND (d.VIGENTE_HASTA IS NULL OR d.VIGENTE_HASTA >= CAST(GETDATE() AS DATE))
WHERE   l.ACTIVO = 1
GROUP BY l.CODIGO;
GO
